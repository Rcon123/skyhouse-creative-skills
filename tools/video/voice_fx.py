#!/usr/bin/env python3
"""Seat a clean voice in a room, the way a phone would have recorded it.

A dry text-to-speech read over phone footage is an instant tell. Measured on Ryan's own winning
videos (voice_profile.py, 2026-10-05): the gaps between words sit 21 to 32 dB under the speech,
never silent; the voice decays 5 to 17 dB in the 100 ms after a word (a room); 95% of the energy
is under about 3 kHz. Clean TTS measured 56 to 60 dB, 24 to 31 dB and 6.5 kHz.

  tools/video/.venv/bin/python tools/video/voice_fx.py IN.wav OUT.wav [--preset kitchen-phone]

Presets only change the channel (band, room, level, floor). They never change timing, so a voice
processed here still drives lip sync frame for frame.
"""
import subprocess
import sys

PRESETS = {
    # rt60: how long the room rings (s). wet_db: room level under the dry voice. floor_db: noise in the gaps (dBFS).
    # phone held at arm's length in a hard-surfaced kitchen
    "kitchen-phone": {"rt60": 0.38, "wet_db": -12, "predelay_ms": 6, "lowpass": 7000, "shelf_db": -5, "floor_db": -52, "aac_kbps": 64},
    # phone propped on a dashboard: small padded space, little ring, more hiss
    "car-phone": {"rt60": 0.16, "wet_db": -13, "predelay_ms": 3, "lowpass": 6500, "shelf_db": -6, "floor_db": -48, "aac_kbps": 64},
    # a camera a few feet away in a kitchen or living room (drama scenes)
    "room-camera": {"rt60": 0.5, "wet_db": -6, "predelay_ms": 12, "lowpass": 8500, "shelf_db": -3, "floor_db": -54, "aac_kbps": 96},
    # for a voice generated by a video model: the performance is already human, the track is too clean.
    # On 2026-10-05 this took a Seedance 2 mini voice from 2/10 to 9 and 10/10 with the listening judge,
    # and did nothing for a text-to-speech read (3/10), so it is not just fooling the judge with hiss.
    "native-kitchen": {"rt60": 0.42, "wet_db": -10, "predelay_ms": 6, "lowpass": 7000, "shelf_db": -5, "floor_db": -40, "aac_kbps": 64},
    "native-room": {"rt60": 0.5, "wet_db": -8, "predelay_ms": 12, "lowpass": 8500, "shelf_db": -3, "floor_db": -42, "aac_kbps": 96},
    # a second person a few feet from a lav mic that is clipped on someone else (the off-camera
    # granddaughter in TPS VID636 measured: rolloff 1.6 to 2.0 kHz, gaps 22 to 30 dB down, no close presence)
    "native-offmic": {"rt60": 0.45, "wet_db": -5, "predelay_ms": 10, "lowpass": 2300, "shelf_db": -8, "floor_db": -44, "aac_kbps": 48},
    # barely there: for voices that already carry some room
    "light": {"rt60": 0.25, "wet_db": -15, "predelay_ms": 5, "lowpass": 8000, "shelf_db": -3, "floor_db": -56, "aac_kbps": 96},
}
SR = 48000


def _run(cmd):
    subprocess.run(cmd, check=True, stdin=subprocess.DEVNULL)


def _room_ir(rt60, predelay_ms, seed=7):
    """A small synthetic room: a few early reflections, then a noise tail that falls 60 dB in rt60 seconds."""
    import numpy as np
    rng = np.random.default_rng(seed)
    n = int(SR * (rt60 * 1.3 + 0.05))
    t = np.arange(n) / SR
    tail = rng.standard_normal(n) * np.exp(-6.91 * t / rt60)
    # rooms eat highs faster than lows
    from scipy import signal
    b, a = signal.butter(2, 4500 / (SR / 2))
    tail = signal.lfilter(b, a, tail)
    ir = np.zeros(n + int(SR * 0.06))
    start = int(SR * predelay_ms / 1000)
    ir[start:start + n] += tail * 0.5
    for ms, g in ((predelay_ms + 5, 0.55), (predelay_ms + 11, 0.4), (predelay_ms + 19, 0.3), (predelay_ms + 29, 0.2)):
        ir[int(SR * ms / 1000)] += g * rng.choice([-1, 1])
    return ir / np.sqrt((ir ** 2).sum())


def apply(src, dst, preset="kitchen-phone"):
    import numpy as np
    from scipy import signal
    from scipy.io import wavfile
    p = PRESETS[preset] if isinstance(preset, str) else preset
    tmp_in, tmp_mid, tmp_aac = dst + ".in.wav", dst + ".mid.wav", dst + ".tmp.m4a"
    _run(["ffmpeg", "-nostdin", "-y", "-loglevel", "error", "-i", src, "-ar", str(SR), "-ac", "1", "-c:a", "pcm_s16le", tmp_in])
    sr, x = wavfile.read(tmp_in)
    x = x.astype(np.float64) / 32768.0
    n = len(x)
    wet = signal.fftconvolve(x, _room_ir(p["rt60"], p["predelay_ms"]))[:n]
    y = x + wet * (10 ** (p["wet_db"] / 20))
    rng = np.random.default_rng(11)
    noise = rng.standard_normal(n)
    b, a = signal.butter(2, [120 / (SR / 2), 3500 / (SR / 2)], btype="band")
    noise = signal.lfilter(b, a, noise)
    noise *= (10 ** (p["floor_db"] / 20)) / (np.sqrt((noise ** 2).mean()) + 1e-12)
    y = y + noise
    y = y / max(1.0, np.abs(y).max() / 0.9)
    wavfile.write(tmp_mid, SR, (y * 32767).astype(np.int16))
    chain = (f"highpass=f=110,lowpass=f={p['lowpass']},highshelf=f=4800:g={p['shelf_db']},"
             "acompressor=threshold=-20dB:ratio=3:attack=8:release=160:makeup=2")
    # one pass through a low-bitrate AAC encode adds the codec texture every phone upload has
    _run(["ffmpeg", "-nostdin", "-y", "-loglevel", "error", "-i", tmp_mid, "-af", chain, "-ar", str(SR), "-ac", "1",
          "-c:a", "aac", "-b:a", f"{p['aac_kbps']}k", tmp_aac])
    _run(["ffmpeg", "-nostdin", "-y", "-loglevel", "error", "-i", tmp_aac, "-af", f"apad=whole_len={n},atrim=end_sample={n}",
          "-ar", str(SR), "-ac", "1", "-c:a", "pcm_s16le", dst])
    for f in (tmp_in, tmp_mid, tmp_aac):
        subprocess.run(["rm", "-f", f])
    return dst


if __name__ == "__main__":
    a = [x for x in sys.argv[1:] if not x.startswith("--")]
    preset = sys.argv[sys.argv.index("--preset") + 1] if "--preset" in sys.argv else "kitchen-phone"
    print(apply(a[0], a[1], preset))
